import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import type { AstroIntegration } from "astro";

import { CSP_HEADER_DIRECTIVES } from "../src/shared/constants/csp";
import { cspHeaderValue } from "./csp-serialization";

/** Header name/value pairs used by both the Worker and the static `_headers` file. */
const SECURITY_HEADERS: Readonly<Record<string, string>> = {
  "Content-Security-Policy": cspHeaderValue(CSP_HEADER_DIRECTIVES),
  "X-Content-Type-Options": "nosniff",
  "X-Frame-Options": "DENY",
  "Referrer-Policy": "no-referrer",
  "Permissions-Policy": "camera=(self), microphone=(), geolocation=()",
};

const HEADERS_BEGIN =
  "# BEGIN security headers (generated by plugins/security-headers-file.ts; do not edit)";
const HEADERS_END = "# END security headers";
const LEGACY_MARKER =
  "# Generated by plugins/security-headers-file.ts from src/shared/server/middleware/security-headers.ts. Do not edit by hand.";

function stripLegacyBlock(existing: string): string {
  const start = existing.indexOf(LEGACY_MARKER);

  if (start === -1) {
    return existing;
  }

  const end = existing.indexOf("\n\n", start);

  return end === -1 ? existing : existing.slice(end + 2).replace(/^\n+/u, "");
}

function replaceBlock(existing: string, block: string): string {
  const trimmed = stripLegacyBlock(existing);
  const start = trimmed.indexOf(HEADERS_BEGIN);
  const end = start === -1 ? -1 : trimmed.indexOf(HEADERS_END, start);

  if (start === -1 || end === -1) {
    return trimmed.length === 0 ? block : `${block}\n${trimmed}`;
  }

  const before = trimmed.slice(0, start);
  const after = trimmed.slice(end + HEADERS_END.length).replace(/^\n+/u, "");

  return `${before}${block}${after.length === 0 ? "" : `\n${after}`}`;
}

export interface SecurityHeadersFileOptions {
  /** Output filename inside Astro's build directory. */
  fileName: string;
}

/** Generate Cloudflare's static headers file from the shared definitions. */
export function securityHeadersFile(options: SecurityHeadersFileOptions): AstroIntegration {
  return {
    name: "security-headers",
    hooks: {
      "astro:build:done": async ({ dir, logger }) => {
        const headersUrl = new URL(options.fileName, dir);
        const existing = await readFile(headersUrl, "utf8").catch(() => "");
        const block = [
          HEADERS_BEGIN,
          "/*",
          ...Object.entries(SECURITY_HEADERS).map(([name, value]) => `  ${name}: ${value}`),
          HEADERS_END,
          "",
        ].join("\n");
        const content = replaceBlock(existing, block);

        await writeFile(headersUrl, content);
        logger.debug(`Updated ${fileURLToPath(headersUrl)}`);
      },
    },
  };
}
